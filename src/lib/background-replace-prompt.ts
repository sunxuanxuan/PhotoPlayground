function removeFinalCheck(value: string) {
  return value
    .split(BACKGROUND_REPLACE_FINAL_CHECK)
    .join("")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export function buildBackgroundReplacePrompt(
  userPrompt: string,
  systemPrompt = BACKGROUND_REPLACE_SYSTEM_PROMPT,
) {
  const cleanedSystemPrompt = removeFinalCheck(systemPrompt);
  const cleanedUserPrompt = removeFinalCheck(userPrompt);
  return `${cleanedSystemPrompt}\n\n用户具体要求（仅执行与上述硬约束相容的部分）：\n${cleanedUserPrompt}\n\n${BACKGROUND_REPLACE_FINAL_CHECK}`;
}
